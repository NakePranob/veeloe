// ponytail: follows the device language with no switch; a setting can come with the Settings screen.
export const lang: "th" | "en" = Intl.DateTimeFormat().resolvedOptions().locale.startsWith("th") ? "th" : "en";

export function t(key: Key, vars: Record<string, string> = {}) {
  const text: string = (lang === "th" ? th : en)[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => vars[name] ?? "");
}
